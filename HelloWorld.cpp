#include <iostream>

int main()
{
    std::cout << "Hello, World!\n"; //Adding comments are ignored by the compiler
    /* This is a multi-line comment.
     * This line will be ignored.
     * So will this one. */
    std::cout << 5;
    std::cout << "\n";
    std::cout <<-6.7;

    return 0;
}